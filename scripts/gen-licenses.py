def go_mod_dir(cache, mod, ver):
    enc = re.sub(r"[A-Z]", lambda m: "!" + m.group(0).lower(), mod)
    return os.path.join(cache, f"{enc}@{ver}")


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read().replace("\r\n", "\n").strip() + "\n"


def parse_gomods(path):
    mods = []
    for line in open(path, encoding="utf-8"):
        f = line.split()
        if len(f) >= 3 and f[0] == "dep":
            mods.append((f[1], f[2]))
    return mods


def parse_deps(path):
    res = {}
    for line in open(path, encoding="utf-8"):
        if "(c)" in line or "(n)" in line:
            continue
        m = re.search(r"--- ([\w.\-]+):([\w.\-]+):([\w.\-+\[\]]+)(?: -> ([\w.\-]+))?", line)
        if not m:
            continue
        g, a, v, v2 = m.groups()
        res[(g, a)] = v2 or v
    return res


def android_license(group):
    best = None
    for key in ANDROID_LICENSES:
        if group == key or group.startswith(key + "."):
            if best is None or len(key) > len(best):
                best = key
    return ANDROID_LICENSES.get(best) if best else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gomods", required=True)
    ap.add_argument("--deps", required=True)
    ap.add_argument("--gomodcache", default=os.path.expanduser("~/go/pkg/mod"))
    ap.add_argument("--goroot", default=os.path.expanduser("~/.cache/tailscale-go"))
    ap.add_argument("--tunnel-src", default=os.path.expanduser("~/build/tailscale-android"))
    ap.add_argument("--sdk-version", default="5.5.13")
    a = ap.parse_args()

    out = [HEADER]
    texts = {}  # text -> [jména]
    errors = []

    def add_text(name, text):
        texts.setdefault(text, []).append(name)

    # Go: běhové prostředí + moduly
    gover = "Go"
    for line in open(a.gomods, encoding="utf-8"):
        m = re.search(r":\s+(go[\d.]+)\s*$", line)
        if m:
            gover = m.group(1)
            break
    go_items = []
    lic = os.path.join(a.goroot, "LICENSE")
    pat = os.path.join(a.goroot, "PATENTS")
    t = read(lic) + ("\n" + read(pat) if os.path.exists(pat) else "")
    add_text(f"Go {gover} (runtime a standardní knihovna)", t)
    go_items.append(f"Go {gover} (runtime a standardní knihovna) — BSD-3-Clause")
    for mod, ver in parse_gomods(a.gomods):
        if mod == "github.com/tailscale/tailscale-android":
            d = a.tunnel_src
        else:
            d = go_mod_dir(a.gomodcache, mod, ver)
        if not os.path.isdir(d):
            errors.append(f"chybí zdroj modulu {mod}@{ver} ({d})")
            continue
        files = sorted(f for f in os.listdir(d)
                       if re.match(r"(?i)^(licen[cs]e|copying|patents)(\.md|\.txt)?$", f)
                       and os.path.isfile(os.path.join(d, f)))
        if not files:
            errors.append(f"modul {mod}@{ver} nemá soubor s licencí")
            continue
        t = "\n".join(read(os.path.join(d, f)) for f in files)
        name = f"{mod} {ver}"
        add_text(name, t)
        go_items.append(name)

    # Android knihovny
    android_items = []
    by_lic = {}
    for (g, art), ver in sorted(parse_deps(a.deps).items()):
        if g.startswith("org.linphone"):
            continue
        l = android_license(g)
        if not l:
            errors.append(f"neznámá licence knihovny {g}:{art}:{ver} — doplnit ANDROID_LICENSES")
            continue
        label = {"BSD-3-Clause-protobuf": "BSD-3-Clause", "MIT-checker": "MIT"}.get(l[0], l[0])
        android_items.append(f"{g}:{art}:{ver} — {label}, Copyright (C) {l[1]}")
        by_lic.setdefault(l[0], []).append(f"{g}:{art}")

    if errors:
        for e in errors:
            print("CHYBA:", e, file=sys.stderr)
        sys.exit(1)

    apache = None
    for t, names in texts.items():
        if "Apache License" in t and "Version 2.0" in t and apache is None:
            apache = t

    out.append("\n" + "=" * 72 + "\n1. VOLACÍ KNIHOVNA\n" + "=" * 72 + "\n")
    out.append(SDK_NOTE.format(ver=a.sdk_version))

    out.append("\n" + "=" * 72 + "\n2. KNIHOVNA PRIVÁTNÍ SÍTĚ A JEJÍ SOUČÁSTI\n" + "=" * 72 + "\n")
    out.append("Knihovna je sestavená z tailscale-android (BSD-3-Clause) s úpravami\n"
               "v adresáři tunnel/patches zdrojového kódu aplikace. Obsahuje:\n\n")
    out.extend(f"  - {i}\n" for i in go_items)

    out.append("\n" + "=" * 72 + "\n3. KNIHOVNY ANDROIDU\n" + "=" * 72 + "\n")
    out.extend(f"  - {i}\n" for i in android_items)

    out.append("\n" + "=" * 72 + "\n4. ZNĚNÍ LICENCÍ\n" + "=" * 72 + "\n")
    n = 0
    for t, names in texts.items():
        n += 1
        out.append("\n" + "-" * 72 + "\n" + f"4.{n} Platí pro: " + ", ".join(names) + "\n" + "-" * 72 + "\n\n" + t)
    if "BSD-3-Clause-protobuf" in by_lic:
        n += 1
        out.append("\n" + "-" * 72 + f"\n4.{n} Platí pro: " + ", ".join(by_lic["BSD-3-Clause-protobuf"]) + "\n" + "-" * 72 + "\n\n" + PROTOBUF_BSD)
    if "MIT-checker" in by_lic:
        n += 1
        out.append("\n" + "-" * 72 + f"\n4.{n} Platí pro: " + ", ".join(by_lic["MIT-checker"]) + "\n" + "-" * 72 + "\n\n" + CHECKER_MIT)
    if "Apache-2.0" in by_lic:
        if apache is None:
            print("CHYBA: chybí text Apache-2.0", file=sys.stderr)
            sys.exit(1)
        n += 1
        out.append("\n" + "-" * 72 + f"\n4.{n} Apache License 2.0 — platí pro knihovny Androidu označené Apache-2.0 v oddílu 3\n" + "-" * 72 + "\n\n" + apache)
    n += 1
    out.append("\n" + "-" * 72 + f"\n4.{n} GNU General Public License v3 — aplikace Phone21\n" + "-" * 72 + "\n\n" + read(os.path.join(ROOT, "LICENSE.txt")))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("".join(out))
    print(f"zapsáno {OUT}: {len(go_items)} součástí knihovny sítě, {len(android_items)} knihoven Androidu, {n} znění licencí")


if __name__ == "__main__":
    main()
